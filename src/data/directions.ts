// Single source of truth for the new 4-directions structure.
// Drives the home hub (RouteCards) and the 4 direction pages.
// Content ported from the approved wireframe (wireframe-v2.html) + МАППИНГ_программ.md.

export interface DeepSlot {
  h: string
  t: string
}

export interface Program {
  n: string
  d: string
  f: string
  t: string
  p: string
  deep: DeepSlot[]
}

export interface DirectionCard {
  teaser: string
  tags: string[]
  out: string
  /** Format + duration chips shown on the home cards instead of program names. */
  formats: string[]
}

/** A single audience persona for the «Для кого» block. */
export interface WhoPersona {
  /** Role title, e.g. "Собственник". */
  role: string
  /** One-line descriptor of the role. */
  note: string
  /** Icon key resolved in WhoFor.tsx (owner/lead/tops/team/dept/core/specialist/architect/company/ready). */
  icon: string
}

export interface Direction {
  slug: string
  num: number
  /** Full headline used on the direction page hero. */
  name: string
  /** Shorter title used on home route cards + nav. */
  cardTitle: string
  navLabel: string
  lead: string
  /** Audience personas shown as cards / list in the «Для кого» block. */
  whoPersonas: WhoPersona[]
  /** "Когда берут" trigger line shown under the «Для кого» heading. */
  whoWhen: string
  outs: string[]
  progs: Program[]
  proof: { quote: string; sub: string }
  price: string
  next: string | null
  nextName: string | null
  nextNote: string | null
  card: DirectionCard
}

